"""DevBox Shim 生成与 PATH 管理。

根据当前激活版本生成扁平键格式的 shim.cfg 与各工具 exe 的 bat 转发脚本，
并确保 shim 目录已前置到**系统级** PATH（幂等）。仅依赖 Python 标准库。

设计要点：
- 系统全局 PATH 只永久加入一个固定的 shim 目录（且置于最前），切换版本仅改写 shim.cfg。
- bat 转发脚本每次执行时动态读取同目录的 shim.cfg，因此已打开的终端也能即时生效。
- bat 文件以 GBK 编码写入，模板中的字面量百分号需转义处理。
- 之所以写系统级而非用户级：Windows 为进程构造的生效 PATH = 系统级 PATH + 用户级 PATH，
  系统级在前；若 shim 只在用户级，系统里已有的同名命令（如系统 JDK 的 java.exe）仍会先命中，
  透明代理失效。
"""

import ctypes
from pathlib import Path

from app.providers import PROVIDERS, TOOL_ORDER

# 用户级环境变量所在的注册表子键（HKEY_CURRENT_USER\Environment）
_ENV_KEY = "Environment"

# 系统级环境变量所在的注册表子键（HKEY_LOCAL_MACHINE）
_SYS_ENV_KEY = r"SYSTEM\CurrentControlSet\Control\Session Manager\Environment"

# REG_EXPAND_SZ：系统/用户 PATH 通常为此类型，写回时必须保持一致
_REG_EXPAND_SZ = 2

# shim.cfg 首行注释
_CFG_HEADER = "# DevBox shim targets - generated by DevBox, do not edit manually"

# 单个 bat 转发脚本模板（内联兜底）。
# 注意：本模板通过 % 进行格式化，因此所有字面量百分号都要写成 %%。
# 于是 bat 中的 %%a 在 Python 源码中写作 %%%%a，写出的文件里仍是 %%a；
# 同理 %~dp0 写作 %%~dp0，%T% 写作 %%T%%，而 %* 只需写作 %%*。
# 正常情况下优先从随程序分发的 shim_templates/shim.bat.tpl 读取（见下方加载逻辑）。
_BAT_TEMPLATE_INLINE = r"""@echo off
setlocal
for /f "tokens=2 delims==" %%%%a in ('findstr /b /i "%(tool)s_bin=" "%%~dp0shim.cfg"') do set T=%%%%a
if not defined T echo DevBox: %(tool)s 未选择版本，请先在面板中切换。& exit /b 1
set T=%%T:"=%%
rem 同步当前选中的 JDK 到 JAVA_HOME，使 mvn 等依赖 JAVA_HOME 的子进程使用同一版本
for /f "tokens=2 delims==" %%%%a in ('findstr /b /i "java_home=" "%%~dp0shim.cfg"') do set JH=%%%%a
if defined JH set JH=%%JH:"=%%
if defined JH set "JAVA_HOME=%%JH%%"
if defined JH set "PATH=%%JH%%\bin;%%PATH%%"
if not exist "%%T%%\%(exe)s" echo DevBox: 目标不存在 %%T%%\%(exe)s & exit /b 2
"%%T%%\%(exe)s" %%*
"""


def _load_bat_template():
    """加载 bat 模板文本。

    优先读取随程序分发的资源文件 ``shim_templates/shim.bat.tpl``
    （冻结环境下经 ``app.resource_path`` 基于 ``sys._MEIPASS`` 定位）；
    文件缺失或读取失败时回退到内联模板 ``_BAT_TEMPLATE_INLINE``，行为保持一致。
    """
    try:
        from app import resource_path

        tpl = resource_path("shim_templates") / "shim.bat.tpl"
        if tpl.is_file():
            return tpl.read_text(encoding="utf-8")
    except Exception:  # noqa: BLE001 - 任何异常均回退内联模板
        pass
    return _BAT_TEMPLATE_INLINE


# 模块级模板名：保持可被 "%" 格式化的语义不变。
_BAT_TEMPLATE = _load_bat_template()


def _render_bat(tool, exe):
    """按模板渲染单个 bat 转发脚本内容（返回字符串，尚未编码）。"""
    return _BAT_TEMPLATE % {"tool": tool, "exe": exe}


def write_shims(box):
    """根据 box 当前激活版本生成 shim.cfg 与各工具 bat 转发脚本。

    - 遍历 TOOL_ORDER 中的工具，读取当前版本与安装路径；
    - 为每个存在的 exe 生成同名 bat（如 java.exe -> java.bat）；
    - 生成扁平键格式的 shim.cfg（tool_bin=路径）；
    - 最后确保 shim 目录已前置到系统 PATH。
    """
    shim_dir = Path(box.data["shim_dir"])
    shim_dir.mkdir(parents=True, exist_ok=True)

    # 先清理旧的转发脚本，避免残留过期 shim
    for old in shim_dir.glob("*.bat"):
        try:
            old.unlink()
        except OSError as exc:
            print("[DevBox] 警告：删除旧 shim 失败 %s (%s)" % (old, exc))

    entries = {}  # {f"{tool}_bin": bin_dir_str}，仅记录有效项
    java_home = ""  # 当前选中的 JDK 根目录，写入 shim.cfg 供各 bat 同步 JAVA_HOME
    for tool in TOOL_ORDER:
        ver = box.current(tool)
        if not ver:
            # 未选择版本：不生成脚本，shim.cfg 也不会写出该项
            continue

        rec = box.find_installed(tool, ver)
        if not rec:
            print("[DevBox] 警告：%s 当前版本 %s 未找到安装记录，已跳过。" % (tool, ver))
            continue

        root = rec["path"]
        bin_dir = PROVIDERS[tool].bin_path(root)
        entries["%s_bin" % tool] = str(bin_dir)
        if tool == "java":
            java_home = str(root)

        # 为该 Provider 的每个 exe 生成转发脚本；目标 exe 不存在则跳过
        # （例如老版本 Node 没有 npx.cmd）
        for exe in PROVIDERS[tool].exe_names:
            if not (bin_dir / exe).exists():
                continue
            script = shim_dir / (Path(exe).stem + ".bat")
            try:
                # 规范行尾为 CRLF 并确保末行以 \r\n 结尾，
                # 避免 cmd 对 LF-only / 末行无换行的 bat 解析异常（丢弃末行等）。
                text = _render_bat(tool, exe).replace("\r\n", "\n").replace("\n", "\r\n")
                if not text.endswith("\r\n"):
                    text += "\r\n"
                script.write_bytes(text.encode("gbk"))
            except OSError as exc:
                print("[DevBox] 警告：写入 shim 失败 %s (%s)" % (script, exc))

    # 生成扁平的 shim.cfg。
    # 关键：必须与 bat 转发脚本、cmd 活动代码页(简体中文 Windows 为 GBK/936)保持一致，
    # 用 GBK 写入。bat 通过 findstr 读取本文件的原始字节并 set 到变量，若此处用 UTF-8，
    # 中文路径（如 D:\环境管理）会被 cmd 按 GBK 误解码成乱码，导致 shim 转发"目标不存在"。
    lines = [_CFG_HEADER]
    for tool in TOOL_ORDER:
        key = "%s_bin" % tool
        if key in entries:
            lines.append("%s=%s" % (key, entries[key]))
    if java_home:
        lines.append("java_home=%s" % java_home)
    cfg = shim_dir / "shim.cfg"
    try:
        cfg.write_text("\n".join(lines) + "\n", encoding="gbk")
    except OSError as exc:
        print("[DevBox] 警告：写入 shim.cfg 失败 (%s)" % exc)

    ensure_shim_in_path(shim_dir)


def _read_path(root, sub, name="Path"):
    """读取指定注册表位置的 PATH，返回 ``(值, 类型)``；不存在时返回 ``("", None)``。"""
    try:
        import winreg
    except ImportError:
        return "", None
    try:
        with winreg.OpenKey(root, sub, 0, winreg.KEY_READ) as key:
            value, typ = winreg.QueryValueEx(key, name)
            return value or "", typ
    except OSError:
        return "", None


def _write_path(root, sub, value, typ):
    """以指定类型写入 PATH，返回是否成功（失败仅告警，不抛出）。"""
    try:
        import winreg
    except ImportError:
        return False
    try:
        with winreg.OpenKey(root, sub, 0, winreg.KEY_SET_VALUE) as key:
            winreg.SetValueEx(key, "Path", 0, typ, value)
        return True
    except OSError as exc:
        print("[DevBox] 警告：写入注册表 PATH 失败 (%s)" % exc)
        return False


def _broadcast_env_change():
    """广播 WM_SETTINGCHANGE，通知系统刷新环境变量（尽力而为，失败不影响主流程）。"""
    try:
        HWND_BROADCAST = 0xFFFF
        WM_SETTINGCHANGE = 0x001A
        SMTO_ABORTIFHUNG = 0x0002
        result = ctypes.c_ulong()
        ctypes.windll.user32.SendMessageTimeoutW(
            HWND_BROADCAST,
            WM_SETTINGCHANGE,
            0,
            ctypes.c_wchar_p("Environment"),
            SMTO_ABORTIFHUNG,
            5000,
            ctypes.byref(result),
        )
    except Exception:
        pass


def ensure_shim_in_path(shim_dir):
    """确保 shim 目录位于**系统级 PATH 的最前面**，并从用户级 PATH 中移除（幂等）。

    为什么必须写系统级并前置：
      Windows 为每个新进程构造的生效 PATH = 系统级 PATH + 用户级 PATH，系统级在前。
      若只把 shim 放到用户级 PATH 首位，系统里已有的同名命令（如
      ``C:\\Program Files\\...\\jdk-17\\bin\\java.exe``）仍会被先命中，导致
      ``java -version`` 指向系统 JDK 而非 GUI 选中的版本。只有把 shim 前置到系统级
      PATH，才能实现真正的全局命令透明代理。

    同时把用户级 PATH 中的 shim 条目清除，避免两处重复（PATH 无冗余）。

    返回 True 表示本次修改了 PATH，False 表示无需修改（或写入失败）。
    """
    try:
        import winreg
    except ImportError:
        return False

    shim = str(shim_dir).rstrip(";\\")
    target = shim.lower()

    def _norm(item):
        return str(item).strip().strip(";").rstrip("\\").lower()

    sys_path, sys_type = _read_path(winreg.HKEY_LOCAL_MACHINE, _SYS_ENV_KEY)
    usr_path, usr_type = _read_path(winreg.HKEY_CURRENT_USER, _ENV_KEY)

    sys_entries = [e for e in sys_path.split(";") if e.strip()]
    usr_entries = [e for e in usr_path.split(";") if e.strip()]

    sys_ok = bool(sys_entries) and _norm(sys_entries[0]) == target
    usr_has = any(_norm(e) == target for e in usr_entries)

    if sys_ok and not usr_has:
        return False

    # 系统级：移除既有 shim 条目后前置，保证优先级最高
    new_sys = ";".join([shim] + [e for e in sys_entries if _norm(e) != target])
    # 用户级：移除 shim 条目，避免与系统级重复
    new_usr = ";".join(e for e in usr_entries if _norm(e) != target)

    combined = new_sys + ";" + new_usr
    # 进程环境块总长上限约 32767；留出余量，超长时告警并放弃，避免破坏 PATH
    if len(combined) > 30000:
        print(
            "[DevBox] 警告：PATH 过长（%d 字符），为避免截断已跳过写入；"
            "请手动把 %s 放到系统 PATH 最前面。" % (len(combined), shim)
        )
        return False

    if sys_ok:
        # 系统级已就绪，仅需清理用户级可能存在的重复项
        if usr_has:
            _write_path(
                winreg.HKEY_CURRENT_USER, _ENV_KEY, new_usr, usr_type or _REG_EXPAND_SZ
            )
        return False

    if _write_path(
        winreg.HKEY_LOCAL_MACHINE, _SYS_ENV_KEY, new_sys, sys_type or _REG_EXPAND_SZ
    ):
        # 成功写入系统级：同时清理用户级重复项
        if usr_has:
            _write_path(
                winreg.HKEY_CURRENT_USER, _ENV_KEY, new_usr, usr_type or _REG_EXPAND_SZ
            )
        print("已将 shim 目录前置到系统 PATH，请新开一个终端。")
        _broadcast_env_change()
        return True

    # 无管理员权限写系统级失败：退化为用户级前置（可能无法覆盖系统 PATH 中的同名命令）
    fallback = ";".join([shim] + [e for e in usr_entries if _norm(e) != target])
    if _write_path(
        winreg.HKEY_CURRENT_USER, _ENV_KEY, fallback, usr_type or _REG_EXPAND_SZ
    ):
        print(
            "[DevBox] 提示：无管理员权限，shim 已加入用户 PATH；"
            "若系统 PATH 中已有同名命令，请以管理员身份运行以写入系统 PATH。"
        )
        _broadcast_env_change()
        return True
    return False
